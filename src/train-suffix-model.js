import { readFileSync, writeFileSync } from "node:fs";
import { SUFFIX_SYMBOLS, SUFFIX_HISTORY_START, suffixContexts } from "./suffix-context.js";
import { collectPublicUrls } from "./suffix-datasets.js";

const [datasetPath, holdoutPath, outputPath] = process.argv.slice(2);
if (!datasetPath || !holdoutPath || !outputPath) {
  throw new Error("Usage: node src/train-suffix-model.js <ada-urls.txt> <holdout-urls.txt> <output.js>");
}

const { training } = collectPublicUrls(readFileSync(datasetPath, "utf8"), readFileSync(holdoutPath, "utf8"));
if (!training.length) throw new Error("No training URLs found");
const counts = new Map();
for (const url of training) {
  const tail = url.href.slice(url.origin.length + 1) + "\0";
  for (let position = 0; position < tail.length; position++) {
    const symbol = SUFFIX_SYMBOLS.indexOf(tail[position]);
    if (symbol === -1) continue;
    const keys = suffixContexts(tail[position - 1] ?? SUFFIX_HISTORY_START, tail[position - 2] ?? SUFFIX_HISTORY_START, tail[position - 3] ?? SUFFIX_HISTORY_START);
    for (const key of keys) {
      let frequencies = counts.get(key);
      if (!frequencies) counts.set(key, frequencies = new Uint32Array(SUFFIX_SYMBOLS.length));
      frequencies[symbol]++;
    }
  }
}

const packed = [];
let contexts = 0;
for (const key of [...counts.keys()].sort()) {
  const frequencies = counts.get(key);
  const support = frequencies.reduce((sum, count) => sum + count, 0);
  if (key.length >= 3 && support < 50) continue;
  const symbols = [...frequencies.keys()].filter(index => frequencies[index] >= (key.length < 3 ? 1 : 3));
  if (key.length >= 3) symbols.sort((left, right) => frequencies[right] - frequencies[left] || left - right).splice(12);
  if (!symbols.length) continue;
  packed.push(key.length, ...Buffer.from(key), symbols.length);
  for (const symbol of symbols) {
    packed.push(symbol);
    let count = frequencies[symbol];
    while (count >= 128) {
      packed.push((count & 127) | 128);
      count >>>= 7;
    }
    packed.push(count);
  }
  contexts++;
}

const rows = Buffer.from(packed).toString("base64url").match(/.{1,120}/g);
const generated = `// Generated by src/train-suffix-model.js. These counts are part of the suffix v1 wire format.\nexport const SUFFIX_MODEL_V1 = [\n${rows.map(row => `  "${row}",`).join("\n")}\n].join("");\n`;
writeFileSync(outputPath, generated, "utf8");
console.log(JSON.stringify({ trainingUrls: training.length, contexts, modelBytes: packed.length }));
